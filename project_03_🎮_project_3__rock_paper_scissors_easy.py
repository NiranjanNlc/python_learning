import random
from dataclasses import dataclass
import asyncio
import time

@dataclass
class Options :
   options = ["rock","paper","scissors"]
   winingCombination = [("rock","scissors"),("paper","rock"),("scissors","paper")]


def getComputerChoice():
    return random.choice(Options.options)
@dataclass
class NoOfWins:
   user :any
   computer :any

   def determineWinner(self,user_input, computer_input):
    if user_input == computer_input:
          print(f"Both players selected {user_input}. It's a tie!")
          quit()
    elif (user_input,computer_input) in Options.winingCombination:
          print("You win!")
          self.user += 1
    else :
          print("Computer wins!")
          self.computer+=1

   def displayfinalScore(self):
      print("\n=== Final Score ===")
      print(f"User wins : {self.user}")
      print(f"Computer wins : {self.computer}")

noOfWins = NoOfWins(0,0)
while True :
     user_input = input("Enter a choice (rock, paper, scissors):  ")
     if user_input not in Options.options:
          continue
     print(f"You choose {user_input }")
     print("allowing computer to choose ..... Wait for second ")
     time.sleep(2)
     computer_input = getComputerChoice()
     print(f"Computer chose {computer_input}")
     noOfWins.determineWinner(user_input,computer_input)
     if input("Play again? (y/n): ").lower().startswith('y'):
        continue
     else:
          print("Goodbye!")
          break
displayFinalScore = noOfWins.displayfinalScore()